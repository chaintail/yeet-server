#!/usr/bin/env node
// Funded end-to-end test of gas sponsorship (GAS-SPONSORSHIP-DESIGN.md 5.4), in two modes.
//
//   node ops/gas-e2e.mjs --plan      read-only: wallets and balances, fresh dry 1Click quotes for a 5 USDC BUY on the
//                                    all-Solana path and on the Base path, what the person would sign on each, the
//                                    simulations that can run unfunded, and the exact amounts to send where
//   node ops/gas-e2e.mjs --live      refused unless GAS_E2E_CONFIRM=fund-and-trade, YEET_LIVE=1, the kill switch off,
//                                    the test account in YEET_LIVE_ACCOUNTS and every balance at its target; then runs
//                                    ops/user-signed-trade.mjs --broadcast for Solana BUY, Solana SELL, Base BUY
//
// --plan signs nothing, broadcasts nothing, reads no key except deriving the Base gas wallet ADDRESS from its key
// file when YEET_BASE_GAS_WALLET is unset. The test wallet's addresses are public (the builders generated them;
// --test-sol / --test-base override); its key file is not read here.
// RPC: SOLANA_RPC_URL (default https://api.mainnet-beta.solana.com), BASE_RPC_URL (default https://mainnet.base.org).
import {randomBytes} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {usdcBalanceOverride} from '../connector/core/pipeline/base/plan-support.mjs';
import {OneClickClient,CATALOG,findToken,base58Encode} from '../connector/core/trade/router.mjs';
import {createBaseRpc} from '../connector/core/pipeline/base/rpc.mjs';
import {readBaseConfig,USDC_BASE,MAX_USER_GAS,TOPUP_GAS} from '../connector/core/pipeline/base/config.mjs';
import {quoteTopup,readFees,TRANSFER_TX_BYTES} from '../connector/core/pipeline/base/fees.mjs';
import {gasWalletAddress} from '../connector/core/pipeline/base/gas-wallet.mjs';
import {buildTransfer,transferData,payloadOf} from '../connector/core/pipeline/base/source-executor.mjs';
import {safeError} from '../connector/core/pipeline/base/safe-error.mjs';
import {createRelayRpc} from '../connector/core/pipeline/solana/relay-rpc.mjs';
import {buildLegTransaction,DEFAULT_COMPUTE_UNIT_LIMIT,DEFAULT_PRIORITY_MICRO_LAMPORTS} from '../connector/core/pipeline/solana/transfer-leg.mjs';
import {USDC_SOLANA,TOKEN_PROGRAM,decodeTransaction} from '../connector/core/pipeline/solana/message.mjs';
import {privyRpcBody} from '../connector/core/pipeline/wallet-request.mjs';
import {usdcOn} from '../connector/core/pipeline/oneclick-leg.mjs';

const here=path.dirname(fileURLToPath(import.meta.url));
const arg=n=>{const i=process.argv.indexOf(`--${n}`);return i>0?process.argv[i+1]:undefined};
const mode=process.argv.includes('--live')?'live':process.argv.includes('--plan')?'plan':null;
if(!mode){console.error('usage: node ops/gas-e2e.mjs --plan | --live');process.exit(2)}

// Public addresses of the test wallet (build-A-solana.md, generated by ops/test-wallet-init.mjs).
const TEST={sol:arg('test-sol')??'3pdbUF2a37ANMsnvCHK4PdtvHCnxobF81ULE3rht8mVq',base:(arg('test-base')??'0xF5a10e30573c215bF2120Dc4990cfA1c9Cb23183')};
const USDC_IN=5_000_000n;// 5 USDC
// Design 5.4 funding targets.
const TARGET={gasWalletWei:2_000_000_000_000_000n,feePayerLamports:50_000_000n,testSolUsdc:8_000_000n,testBaseUsdc:6_000_000n};
const RENT_LAMPORTS=2_039_280n;

const solUrl=process.env.SOLANA_RPC_URL?.trim()||'https://api.mainnet-beta.solana.com';
const baseUrl=process.env.BASE_RPC_URL?.trim()||'https://mainnet.base.org';
const sol=createRelayRpc({readUrl:solUrl});
const base=createBaseRpc({url:baseUrl,env:{}});// env {}: the adapter's broadcast gate stays closed in this process
const cfg=readBaseConfig(process.env);
const oneclick=new OneClickClient({timeoutMs:15_000});
const out={mode,at:new Date().toISOString(),rpc:{solana:solUrl.replace(/\/\/([^/]+)\/.*/,'//$1/…'),base:baseUrl.replace(/\/\/([^/]+)\/.*/,'//$1/…')}};
const step=async(fn)=>{try{return await fn()}catch(e){return {error:safeError(e)}}};
const fmt=(raw,dec)=>{const s=String(raw).padStart(dec+1,'0');return `${s.slice(0,-dec)}.${s.slice(-dec)}`.replace(/\.?0+$/,'')||'0'};
async function solJson(method,params){
 const r=await fetch(solUrl,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({jsonrpc:'2.0',id:1,method,params})});
 const j=await r.json();if(j.error)throw Error(`${method}: ${j.error.message}`);return j.result;
}
const solUsdc=async owner=>{const r=await solJson('getTokenAccountsByOwner',[owner,{mint:USDC_SOLANA},{encoding:'jsonParsed',commitment:'confirmed'}]);
 return (r?.value??[]).reduce((a,x)=>a+BigInt(x.account.data.parsed.info.tokenAmount.amount),0n)};
async function baseJson(method,params){
 const r=await fetch(baseUrl,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({jsonrpc:'2.0',id:1,method,params})});
 const j=await r.json();if(j.error)throw Error(`${method}: ${j.error.message}`);return j.result;
}

// 1. Wallets and balances.
const gasWallet=await step(async()=>cfg.gasWallet??gasWalletAddress(cfg.keyFile));// address only
const feePayer=arg('fee-payer')??process.env.YEET_SOL_FEE_PAYER_ADDRESS?.trim()??null;
out.base_gas_wallet=typeof gasWallet==='string'?{address:gasWallet,eth_wei:await step(async()=>String(await base.balance(gasWallet,'latest')))}:{address:null,...gasWallet};
out.solana_fee_payer=feePayer?{address:feePayer,lamports:await step(async()=>String(await sol.balance(feePayer)))}
 :{address:null,note:'not created yet: the Privy fee-payer server wallet is made by ops/fee-payer-bootstrap.mjs --create (owner step)'};
out.test_wallet={
 solana:{address:TEST.sol,lamports:await step(async()=>String(await sol.balance(TEST.sol))),usdc_raw:await step(async()=>String(await solUsdc(TEST.sol)))},
 base:{address:TEST.base,eth_wei:await step(async()=>String(await base.balance(TEST.base,'latest'))),usdc_raw:await step(async()=>String(await base.tokenBalance(TEST.base)))},
};

// 2. Fresh dry 1Click quotes, 5 USDC -> $WIF.
const wif=CATALOG.find(c=>c.chain==='solana'&&(c.symbol==='WIF'||c.listedSymbol==='$WIF'));
const quote=async origin=>step(async()=>{
 const refundTo=origin.chain==='solana'?TEST.sol:TEST.base;
 const r=await oneclick.quote({dry:true,swapType:'EXACT_INPUT',slippageTolerance:100,originAsset:origin.assetId,depositType:'ORIGIN_CHAIN',destinationAsset:wif.assetId,
  amount:String(USDC_IN),refundTo,refundType:'ORIGIN_CHAIN',recipient:TEST.sol,recipientType:'DESTINATION_CHAIN',deadline:new Date(Date.now()+30*60_000).toISOString()});
 const q=r.quote;
 return {origin:origin.assetId,destination:wif.assetId,amount_in:fmt(q.amountIn,6),amount_out:q.amountOutFormatted??fmt(q.amountOut,wif.decimals),
  min_out:q.minAmountOut?fmt(q.minAmountOut,wif.decimals):null,eta_s:q.timeEstimate??null,deposit_address:q.depositAddress??'(none on a dry quote)'};
});
out.quote_solana_path=await quote(usdcOn('sol',CATALOG));
out.quote_base_path=await quote(usdcOn('base',CATALOG));

// 3. What the person signs on the Solana path (a placeholder deposit address: a dry quote issues none).
const placeholderSol=base58Encode(randomBytes(32));
out.solana_sign=await step(async()=>{
 const fp=feePayer??base58Encode(randomBytes(32));
 const {blockhash}=await sol.latestBlockhash();
 const bytes=buildLegTransaction({feePayer:fp,wallet:TEST.sol,depositOwner:placeholderSol,mint:USDC_SOLANA,tokenProgram:TOKEN_PROGRAM,amount:USDC_IN,decimals:6},{blockhash,createDestination:true});
 const tx=decodeTransaction(bytes),b64=Buffer.from(bytes).toString('base64');
 const req={kind:'solana_tx',payload:{transaction_base64:b64,last_valid_block_height:'0'}};
 const fee=2n*5000n+(BigInt(DEFAULT_COMPUTE_UNIT_LIMIT)*DEFAULT_PRIORITY_MICRO_LAMPORTS+999_999n)/1_000_000n;
 const sim=feePayer?await step(async()=>{const s=await sol.simulate(bytes);return {err:s.err??null,logs:(s.logs??[]).slice(-3)}}):{skipped:'no fee payer yet: a simulation needs signer 0 to exist with SOL'};
 return {signers:[`fee payer ${fp.slice(0,6)}… (signer 0, YEET${feePayer?'':', placeholder'})`,`test wallet ${TEST.sol.slice(0,6)}… (signer 1, the person)`],
  instructions:['ComputeBudget SetComputeUnitLimit 80000',`ComputeBudget SetComputeUnitPrice ${DEFAULT_PRIORITY_MICRO_LAMPORTS} micro-lamports`,
   'AssociatedToken CreateIdempotent (payer = fee payer, owner = deposit address, mint = USDC)','Token TransferChecked 5 USDC, authority = the person'],
  wire_bytes:bytes.length,signatures:tx.signatures.length,privy_rpc:{...privyRpcBody(req),params:{...privyRpcBody(req).params,transaction:`${b64.slice(0,24)}… (${b64.length} chars)`}},
  our_cost_lamports:{fee:String(fee),deposit_account_rent:String(RENT_LAMPORTS)},simulation:sim};
});

// 4. What the person signs on the Base path, with a placeholder deposit address. The simulation overrides the test
// wallet's USDC balance in the call only (FiatToken v2.2 balance mapping at slot 9), since the wallet is unfunded.
const placeholderBase='0x'+randomBytes(20).toString('hex');
out.base_sign=await step(async()=>{
 const data=transferData(placeholderBase,USDC_IN),from=TEST.base.toLowerCase();
 const override=usdcBalanceOverride(from,USDC_IN);
 const call={from,to:USDC_BASE,data};
 const real=await step(async()=>/^0x0{63}1$/.test(await base.call(call))?'true':'false');
 const withBalance=await step(async()=>/^0x0{63}1$/.test(await baseJson('eth_call',[call,'latest',override]))?'true':'false');
 const est=await step(async()=>String(BigInt(await baseJson('eth_estimateGas',[call,'latest',override]))));
 const fees=await readFees(base,cfg.maxFeeWei),l1=BigInt(await base.l1FeeUpperBound(TRANSFER_TX_BYTES));
 const gasEst=typeof est==='string'?BigInt(est):78_737n,gas=gasEst+(gasEst+3n)/4n;
 if(gas>MAX_USER_GAS)throw Error(`gas ${gas} over the guard`);
 const nonce=Number(await base.nonce(from,'pending'));
 const tx=buildTransfer({depositAddress:placeholderBase,amountRaw:USDC_IN,nonce,gas,maxFeePerGas:fees.maxFeePerGas,maxPriorityFeePerGas:fees.maxPriorityFeePerGas});
 const req={kind:'evm_tx',payload:payloadOf(tx)};
 const needed=gas*fees.maxFeePerGas+l1,top=await quoteTopup(base,{capWei:cfg.maxFeeWei});
 const margin=(needed+3n)/4n>2n*TOPUP_GAS*fees.maxFeePerGas?(needed+3n)/4n:2n*TOPUP_GAS*fees.maxFeePerGas;
 return {payload:req.payload,privy_rpc:privyRpcBody(req),gas_source:typeof est==='string'?'eth_estimateGas with the USDC balance overridden':'design measurement 78,737 (estimate failed)',
  simulation:{transfer_eth_call_as_is:real,transfer_eth_call_with_5_usdc:withBalance,estimate_gas:est},
  topup_plan:{needed_wei:String(needed),topup_amount_wei:String(needed+margin),topup_fee_wei:String(top.fee),our_cost_wei:String(needed+margin+top.fee)}};
});

// 5. Prices and the funding asks.
const tokens=await step(()=>oneclick.getTokens());
const price=(sym,chain)=>Array.isArray(tokens)?tokens.find(t=>t.symbol===sym&&t.blockchain===chain)?.price??null:null;
const ethUsd=price('ETH','base')??price('ETH','eth'),solUsd=price('SOL','sol');
out.prices_usd={eth:ethUsd,sol:solUsd};
const need=(target,have)=>{try{const h=BigInt(have);return h>=target?0n:target-h}catch{return target}};
const usd=(raw,dec,p)=>p==null?null:Number((Number(fmt(raw,dec))*p).toFixed(2));
const asks=[
 {what:'Base gas wallet ETH',chain:'Base',to:out.base_gas_wallet.address,amount:need(TARGET.gasWalletWei,out.base_gas_wallet.eth_wei),dec:18,unit:'ETH',p:ethUsd},
 {what:'Solana fee payer SOL',chain:'Solana',to:out.solana_fee_payer.address??'(create it first: ops/fee-payer-bootstrap.mjs --create)',amount:need(TARGET.feePayerLamports,out.solana_fee_payer.lamports??'0'),dec:9,unit:'SOL',p:solUsd},
 {what:'Test wallet USDC on Solana',chain:'Solana',to:TEST.sol,amount:need(TARGET.testSolUsdc,out.test_wallet.solana.usdc_raw),dec:6,unit:'USDC',p:1},
 {what:'Test wallet USDC on Base',chain:'Base',to:TEST.base,amount:need(TARGET.testBaseUsdc,out.test_wallet.base.usdc_raw),dec:6,unit:'USDC',p:1},
];
out.funding_asks=asks.map(a=>({what:a.what,chain:a.chain,to:a.to,amount:`${fmt(a.amount,a.dec)} ${a.unit}`,usd:usd(a.amount,a.dec,a.p)}));
out.funding_total_usd=Number(out.funding_asks.reduce((s,a)=>s+(a.usd??0),0).toFixed(2));
out.test_wallet_eth_and_sol='0: the test wallet holds no ETH and no SOL; the gas wallet and the fee payer pay';

if(mode==='plan'){
 console.log(JSON.stringify(out,null,1));
 console.log('\nFUNDING ASKS (send exactly these, nothing to the test wallet in ETH or SOL):');
 for(const a of out.funding_asks)console.log(`  ${a.what.padEnd(28)} ${a.amount.padEnd(16)} ${a.usd===null?'':'~$'+a.usd.toFixed(2)}  ${a.chain}: ${a.to}`);
 console.log(`  total ~$${out.funding_total_usd.toFixed(2)}`);
 process.exit(0);
}

// --live: every refusal before anything runs.
const refuse=why=>{console.error(`--live refused: ${why}`);process.exit(3)};
if(process.env.GAS_E2E_CONFIRM!=='fund-and-trade')refuse('set GAS_E2E_CONFIRM=fund-and-trade');
if(process.env.YEET_LIVE!=='1'||['1','true','on','yes'].includes(String(process.env.YEET_KILL_SWITCH??'').toLowerCase()))refuse('YEET_LIVE=1 and the kill switch off are required');
if(!feePayer||!out.base_gas_wallet.address)refuse('the fee payer and the gas wallet must both exist');
const short=out.funding_asks.filter(a=>!a.amount.startsWith('0 '));
if(short.length)refuse(`not funded yet: ${short.map(a=>`${a.what} needs ${a.amount}`).join('; ')}`);
const run=a=>{console.log(`> node ops/user-signed-trade.mjs ${a.join(' ')}`);execFileSync(process.execPath,[path.join(here,'user-signed-trade.mjs'),...a],{stdio:'inherit'})};
run(['--chain','sol','--side','buy','--coin','$WIF','--usdc','5','--broadcast']);
run(['--chain','sol','--side','sell','--coin','$WIF','--percent','100','--broadcast']);
run(['--chain','base','--side','buy','--coin','$WIF','--usdc','5','--broadcast']);
